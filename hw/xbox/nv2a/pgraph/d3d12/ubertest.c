static void append_stage_text(GString *out, const char *text,
                              unsigned int stage)
{
    for (const char *p = text; *p != '\0'; p++) {
        g_string_append_c(out, *p == '$' ? (char)('0' + stage) : *p);
    }
}

char *pgraph_d3d12_uber_test_vs_source(void)
{
    return g_strconcat(uber_test_common_hlsl, uber_test_vs_hlsl, NULL);
}

char *pgraph_d3d12_uber_test_ps_source(void)
{
    GString *source = g_string_new(NULL);

    for (unsigned int i = 0; i < NV2A_MAX_TEXTURES; i++) {
        append_stage_text(source, uber_test_ps_decl_hlsl, i);
    }
    g_string_append(source, uber_test_common_hlsl);
    g_string_append(source, uber_test_ps_head_hlsl);
    for (unsigned int i = 0; i < NV2A_MAX_TEXTURES; i++) {
        append_stage_text(source, uber_test_ps_stage_hlsl, i);
    }
    g_string_append(source, uber_test_ps_tail_hlsl);
    return g_string_free(source, FALSE);
}
