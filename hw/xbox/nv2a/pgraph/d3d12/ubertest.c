/*
 * Measurement path (tune "ubertest=<id>"): a representative NV2A
 * interpreter vertex and pixel shader, sized and structured like the
 * fallback shaders, compiled only to time the compilers and the driver. They render nothing meaningful and are never bound.
 *
 * Vertex shader: a loop over up to 136 pre-decoded program steps (two uint4
 * each) switching on the MAC and ILU opcodes, temporaries and inputs behind
 * switch-based helpers, A0-relative constants, select-based write masks,
 * and a fixed-function path with skinning, eight lights and texgen.
 * Pixel shader: four texture stage blocks (stage modes, texture dimension
 * from a constant, samples outside loops), a loop over eight register
 * combiner stages, the final combiner, fog and alpha test.
 *
 * Stage-specific parts use '$' for the stage number.
 */

