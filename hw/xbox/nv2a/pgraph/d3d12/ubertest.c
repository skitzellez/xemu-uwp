    "            dotValue = dot(coord.xyz, dotmap((st.w >> 5u) & 7u, prev));\n"
    "            texel = float4(dotValue, dotValue, dotValue, dotValue);\n"
    "            sampled = false;\n"
    "            break;\n"
    "        default:\n"
    "            break;\n"
    "        }\n"
    "        [flatten] if ((st.w & 8u) != 0u) {\n"
    "            coord.xy /= max(texSize[$u].xy, float2(1.0, 1.0));\n"
    "        }\n"
    "        [branch] if (sampled) {\n"
    "            [branch] switch (st.y) {\n"
    "            case 1u:\n"
    "                texel = texCube$.Sample(samp$, coord.xyz);\n"
    "                break;\n"
    "            case 2u:\n"
    "                texel = texArray$.Sample(samp$, float3(coord.xy, coord.z));\n"
    "                break;\n"
    "            case 3u:\n"
    "                texel = tex3d$.Sample(samp$, coord.xyz);\n"
    "                break;\n"
    "            default:\n"
    "                texel = tex2d$.Sample(samp$, coord.xy);\n"
    "                break;\n"
    "            }\n"
    "            texel = apply_swizzle($u, texel);\n"
    "            [branch] if ((st.w & 16u) != 0u) {\n"
    "                float maxDepth = texel.g > 0.0 ? 16777215.0 :\n"
    "                                 (texel.b > 0.0 ? 511.9375 : 65535.0);\n"
    "                float ref = clamp(coord.z, 0.0, maxDepth);\n"
    "                float lit = compare_float(alphaTest.w, texel.r * maxDepth,\n"
    "                                          ref) ? 1.0 : 0.0;\n"
    "                texel = float4(lit, lit, lit, lit);\n"
    "            }\n"
    "        }\n"
    "        [branch] if (st.x == 7u) {\n"
    "            texel.rgb *= saturate(prev.b * bumpScale[$u] + bumpOffset[$u]);\n"
    "        }\n"
    "        [branch] if ((st.w & 3u) != 0u) {\n"
    "            bool keyed = check_color_key(texel, colorKey[$u],\n"
    "                                         colorKeyMask[$u]);\n"
    "            if (keyed && (st.w & 3u) == 2u) {\n"
    "                discard;\n"
    "            }\n"
    "            if (keyed) {\n"
    "                texel = float4(0.0, 0.0, 0.0, 0.0);\n"
    "            }\n"
    "        }\n"
    "        if ((st.w & 4u) != 0u && texel.a == 0.0) {\n"
    "            discard;\n"
    "        }\n"
    "        dotPrev2 = dotPrev;\n"
    "        dotPrev = dotValue;\n"
    "        t$ = texel;\n"
    "    }\n";

